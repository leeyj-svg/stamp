export const WORD_POOL: string[] = [
  ...WORDS_BY_DIFFICULTY.easy,
  ...WORDS_BY_DIFFICULTY.normal,
  ...WORDS_BY_DIFFICULTY.hard,
];

function shuffle<T>(items: T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

// 난이도에 맞춰 count개 추출. 풀이 모자라면 전체 풀로 보강한다.
export function sampleWords(count: number, difficulty: DifficultyFilter = "all"): string[] {
  let pool = difficulty === "all" ? WORD_POOL : WORDS_BY_DIFFICULTY[difficulty];
  if (pool.length < count) pool = WORD_POOL;
  return shuffle(pool).slice(0, Math.min(count, pool.length));
}
